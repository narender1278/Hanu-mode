const GEMINI_API_KEY = import.meta.env.VITE_GEMINI_API_KEY;
// Use gemini-3.1-flash-lite for ultra-fast (2-3s) generation
const MODEL = import.meta.env.VITE_GEMINI_MODEL || "gemini-3.1-flash-lite";

export async function callGemini(prompt, systemInstruction = "") {
  if (!GEMINI_API_KEY) {
    throw new Error("Missing VITE_GEMINI_API_KEY in .env file.");
  }

  const url = `https://generativelanguage.googleapis.com/v1beta/models/${MODEL}:generateContent?key=${GEMINI_API_KEY}`;

  const payload = {
    contents: [
      {
        role: "user",
        parts: [{ text: prompt }]
      }
    ],
    generationConfig: {
      temperature: 0.2,
      topP: 0.95,
      maxOutputTokens: 2048
    }
  };

  if (systemInstruction) {
    payload.systemInstruction = {
      parts: [{ text: systemInstruction }]
    };
  }

  const response = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(payload)
  });

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Gemini API Error (${response.status}): ${errText}`);
  }

  const data = await response.json();
  const candidate = data.candidates?.[0];
  if (!candidate?.content?.parts?.[0]?.text) {
    throw new Error("No response generated by Gemini.");
  }

  return candidate.content.parts[0].text;
}

export async function generateStudyNotes(topic) {
  const prompt = `You are a principal software engineer and CS educator.
Generate high-yield, concise, master-level study notes for:

Topic: ${topic.title} (ID: ${topic.id})
Section: ${topic.section} / ${topic.subsection}

Format with clean Markdown:
# ${topic.id}: ${topic.title}

## 1. Core Mental Model
- What problem does this solve? Why does it exist? Concise analogy.

## 2. Deep Dive & Code Examples
- Syntax, internals, and 2-3 clean, annotated Python code snippets with outputs.

## 3. Common Pitfalls & Anti-Patterns
- Key bugs, performance edge cases, and how to avoid them.

## 4. Key Takeaways
- Bullet points summarizing essentials.

## 5. Top Interview Questions
- 3 tricky interview questions with concise answers.

Be direct and punchy. Avoid conversational filler.`;

  return await callGemini(prompt);
}

export async function generateQuiz(topic, isRevision = false) {
  const prompt = isRevision
    ? `Create a jumbled revision quiz of 3 questions to test retention on:
Topic: "${topic.title}" (ID: ${topic.id}, Section: ${topic.section}).
Include tricky code-tracing and edge-case questions.

Format output as strict JSON with this exact structure:
{
  "questions": [
    {
      "id": 1,
      "question": "Question text here (can include code snippets)",
      "options": ["A) ...", "B) ...", "C) ...", "D) ..."],
      "correctIndex": 0,
      "explanation": "Why this answer is correct..."
    }
  ]
}`
    : `Create a foundational test quiz of 3 multiple-choice questions for:
Topic: "${topic.title}" (ID: ${topic.id}, Section: ${topic.section}).
Target conceptual clarity and standard syntax.

Format output as strict JSON with this exact structure:
{
  "questions": [
    {
      "id": 1,
      "question": "Question text here",
      "options": ["A) ...", "B) ...", "C) ...", "D) ..."],
      "correctIndex": 0,
      "explanation": "Why this answer is correct..."
    }
  ]
}`;

  const res = await callGemini(
    prompt,
    "You are an automated technical quiz generator. Output ONLY valid JSON without markdown code ticks."
  );

  const clean = res.replace(/```json/g, "").replace(/```/g, "").trim();
  return JSON.parse(clean);
}
